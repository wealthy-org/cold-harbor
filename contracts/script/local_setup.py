#!/usr/bin/env python3
"""LOCAL DEV ONLY. Deploys USDG + mock stock tokens + ColdHarborSettlement to a local anvil and writes web/.env.local.
Uses anvil's public test mnemonic. Never run against a real network."""
import json, subprocess, sys, os

RPC = os.environ.get("RPC", "http://127.0.0.1:8545")
MN = "test test test test test test test test test test test junk"
TICKERS = ["NVDA", "AAPL", "TSLA", "MSFT", "GOOGL", "META", "COIN", "SPY"]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def sh(*a):
    r = subprocess.run(a, capture_output=True, text=True, cwd=root)
    if r.returncode: sys.exit(f"FAILED {a[:4]}: {r.stderr[-400:]}{r.stdout[-200:]}")
    return r.stdout.strip()

def key(i): return sh("cast", "wallet", "private-key", "--mnemonic", MN, "--mnemonic-index", str(i))
def addr(i): return sh("cast", "wallet", "address", "--private-key", key(i))

assert sh("cast", "chain-id", "--rpc-url", RPC) == "31337", "refusing: not a local anvil chain"
owner_pk, owner = key(0), addr(0)
taker, fee_to = addr(1), addr(9)
maker_idx = [5, 6, 7, 8]

def create(contract, *args):
    out = sh("forge", "create", contract, "--rpc-url", RPC, "--private-key", owner_pk, "--broadcast", "--json", "--constructor-args", *args)
    return json.loads(out)["deployedTo"]

usdg = create("test/mocks/MockERC20.sol:MockERC20", "USDG", "USDG", "6")
tokens = {t: create("test/mocks/MockERC20.sol:MockERC20", t, t, "18") for t in TICKERS}
ch = create("src/ColdHarborSettlement.sol:ColdHarborSettlement", usdg, fee_to, "8", owner)
print("settlement", ch)

def send(pk, to, sig, *args):
    sh("cast", "send", to, sig, *args, "--rpc-url", RPC, "--private-key", pk)

for t, a in tokens.items():
    send(owner_pk, ch, "setTokenAllowed(address,bool)", a, "true")
    send(owner_pk, a, "mint(address,uint256)", taker, "100000000000000000000000")        # 100k tokens to the taker
send(owner_pk, usdg, "mint(address,uint256)", taker, "50000000000000")                  # 50M USDG to the taker
for i in maker_idx:
    m, pk = addr(i), key(i)
    send(owner_pk, usdg, "mint(address,uint256)", m, "500000000000000")                 # 500M USDG
    send(pk, usdg, "approve(address,uint256)", ch, "115792089237316195423570985008687907853269984665640564039457584007913129639935")
    for t, a in tokens.items():
        send(owner_pk, a, "mint(address,uint256)", m, "5000000000000000000000000")      # 5M tokens
        send(pk, a, "approve(address,uint256)", ch, "115792089237316195423570985008687907853269984665640564039457584007913129639935")

env = f"""# LOCAL anvil only. Generated by contracts/script/local_setup.py. Keys are anvil's public test keys.
NEXT_PUBLIC_CHAIN_ID=31337
NEXT_PUBLIC_RPC_URL={RPC}
NEXT_PUBLIC_SETTLEMENT={ch}
NEXT_PUBLIC_USDG={usdg}
NEXT_PUBLIC_FEE_BPS=8
NEXT_PUBLIC_TOKENS='{json.dumps(tokens)}'
NEXT_PUBLIC_SIM_QUOTES=1
SIM_QUOTES=1
SIM_MAKER_PKS={",".join(key(i) for i in maker_idx)}
"""
open(os.path.join(root, "..", "web", ".env.local"), "w").write(env)
json.dump({"usdg": usdg, "settlement": ch, "tokens": tokens, "taker": taker}, open(os.path.join(root, "deployments", "chain-31337.json"), "w"), indent=2)
print("taker (anvil #1):", taker)
print("wrote web/.env.local")
