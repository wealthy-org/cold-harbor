#!/usr/bin/env python3
"""After the user's testnet broadcast: verify on chain, prepare sim makers, write web/.env.testnet.
Uses ONLY the throwaway sim-maker keys in .secrets/sim-makers.env. Never the deployer key. Refuses non-46630."""
import json, os, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RPC = os.environ.get("RH_TESTNET_RPC", "https://rpc.testnet.chain.robinhood.com")
MAXU = "115792089237316195423570985008687907853269984665640564039457584007913129639935"

def sh(*a):
    r = subprocess.run(a, capture_output=True, text=True, cwd=root)
    if r.returncode: sys.exit(f"FAILED {' '.join(a[:3])}: {(r.stderr or r.stdout)[-300:]}")
    return r.stdout.strip()
def call(to, sig, *a): return sh("cast", "call", to, sig, *a, "--rpc-url", RPC).split()[0]

assert sh("cast", "chain-id", "--rpc-url", RPC) == "46630", "not testnet"
d = json.load(open(os.path.join(root, "deployments", "rh-testnet.json")))
ch, usdg, toks = d["settlement"], d["usdg"], d["tokens"]

# 1. on-chain verification of the deployment
for name, a in [("settlement", ch), ("usdg", usdg)] + list(toks.items())[:2]:
    assert int(sh("cast", "codesize", a, "--rpc-url", RPC)) > 0, f"no code at {name}"
assert call(ch, "owner()(address)").lower() == d["deployer"].lower(), "owner mismatch"
assert call(ch, "feeBps()(uint16)") == str(d["feeBps"]), "fee mismatch"
assert call(ch, "USDG()(address)").lower() == usdg.lower(), "USDG mismatch"
bad = [t for t, a in toks.items() if call(ch, "tokenAllowed(address)(bool)", a) != "true"]
assert not bad, f"not allowlisted: {bad}"
print(f"verified: {len(toks)} tokens allowlisted, owner/fee/USDG correct")

# 2. prepare sim makers (public mint + approve), keys read from the 0600 file
env = dict(l.split("=", 1) for l in open(os.path.join(root, ".secrets", "sim-makers.env")).read().splitlines() if "=" in l and not l.startswith("#"))
pks = env["SIM_MAKER_PKS"].split(",")
for pk in pks:
    m = sh("cast", "wallet", "address", "--private-key", pk)
    bal = int(sh("cast", "balance", m, "--rpc-url", RPC))
    assert bal > 0, f"maker {m} has no gas ETH (deploy with MAKERS=... first)"
    seq = [(usdg, "mint(address,uint256)", m, "500000000000000"), (usdg, "approve(address,uint256)", ch, MAXU)]
    for t in toks.values():
        seq += [(t, "mint(address,uint256)", m, "5000000000000000000000000"), (t, "approve(address,uint256)", ch, MAXU)]
    for to, sig, *a in seq:
        sh("cast", "send", to, sig, *a, "--rpc-url", RPC, "--private-key", pk)
    print("maker ready", m, "txs", len(seq))

out = f"""# Robinhood Chain TESTNET. Generated by contracts/script/testnet_after_deploy.py
NEXT_PUBLIC_CHAIN_ID=46630
NEXT_PUBLIC_SETTLEMENT={ch}
NEXT_PUBLIC_USDG={usdg}
NEXT_PUBLIC_FEE_BPS={d['feeBps']}
NEXT_PUBLIC_TOKENS='{json.dumps(toks)}'
NEXT_PUBLIC_SIM_QUOTES=1
SIM_QUOTES=1
SIM_MAKER_PKS={env['SIM_MAKER_PKS']}
"""
p = os.path.join(root, "..", "web", ".env.testnet")
open(p, "w").write(out); os.chmod(p, 0o600)
print("wrote web/.env.testnet (copy to .env.local to use)")
